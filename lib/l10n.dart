import 'package:flutter/material.dart';

String tr(BuildContext context, String text) {
  if (context.dependOnInheritedWidgetOfExactType<AppTranslations>() == null) {
    return text;
  }
  final locale = Localizations.localeOf(context);
  final language = locale.scriptCode == 'Hant'
      ? 'zh-Hant'
      : locale.languageCode;
  return switch (language) {
    'en' => _english[text] ?? text,
    'es' => _spanish[text] ?? text,
    'zh-Hant' => _traditionalChinese[text] ?? text,
    _ => text,
  };
}

class AppTranslations extends InheritedWidget {
  const AppTranslations({super.key, required super.child});
  @override
  bool updateShouldNotify(AppTranslations oldWidget) => false;
}

class AppText extends StatelessWidget {
  const AppText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.maxLines,
    this.overflow,
    this.softWrap,
    this.semanticsLabel,
  });
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  final String? semanticsLabel;

  @override
  Widget build(BuildContext context) => Text(
    tr(context, data),
    style: style,
    textAlign: textAlign,
    maxLines: maxLines,
    overflow: overflow,
    softWrap: softWrap,
    semanticsLabel: semanticsLabel,
  );
}

